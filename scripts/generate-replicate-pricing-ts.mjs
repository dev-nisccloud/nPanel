/**
 * Generates packages/api/src/lib/zeepo-replicate-pricing-data.ts from
 * scripts/replicate-pricing-summary.json (official Replicate billingConfig scrape).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const summaryPath = path.join(__dirname, "replicate-pricing-summary.json");
const outPath = path.join(
	__dirname,
	"../packages/api/src/lib/zeepo-replicate-pricing-data.ts",
);

/** @param {string} unit */
function unitSizeFromTitle(unit) {
	const u = unit.toLowerCase();
	if (u.includes("per million")) return 1_000_000;
	if (u.includes("per thousand")) return 1_000;
	return 1;
}

/** @param {string} price */
function parseUsd(price) {
	return Number.parseFloat(price.replace(/[^0-9.]/g, ""));
}

/** @param {import('./replicate-pricing-summary.json')[number]} row */
function normalizeRow(row) {
	if (row.error) {
		const fallback = row.fallbackPrice
			? parseUsd(row.fallbackPrice)
			: null;
		return {
			id: row.id,
			gpuFallbackUsdPerSecond: fallback,
			prices: [],
		};
	}
	return {
		id: row.id,
		prices: row.prices.map((p) => ({
			tier: p.tier,
			metric: p.metric,
			priceUsd: parseUsd(p.price),
			unitSize: unitSizeFromTitle(p.unit),
		})),
	};
}

const summary = JSON.parse(fs.readFileSync(summaryPath, "utf8"));
const models = summary.map(normalizeRow);

const header = `/**
 * Official Replicate model pricing for Zeepo Agent billing.
 * AUTO-GENERATED by scripts/generate-replicate-pricing-ts.mjs - do not edit by hand.
 * Source: scripts/replicate-pricing-summary.json (scraped from replicate.com billingConfig).
 */
`;

const body = `export type ReplicateBillingMetric =
	| "token_input_count"
	| "token_output_count"
	| "image_output_count"
	| "image_input_megapixel_count"
	| "image_output_megapixel_count"
	| "run_count"
	| "video_output_duration_seconds"
	| "video_output_count"
	| "character_input_count";

export type ReplicatePriceEntry = {
	tier: string | null;
	metric: ReplicateBillingMetric;
	/** Dollar amount quoted by Replicate for \`unitSize\` units. */
	priceUsd: number;
	/** Number of metric units covered by \`priceUsd\` (1, 1_000, or 1_000_000). */
	unitSize: number;
};

export type ReplicateModelPricing = {
	id: string;
	prices: ReplicatePriceEntry[];
	/** GPU time fallback when billingConfig is unavailable (e.g. community models). */
	gpuFallbackUsdPerSecond?: number | null;
};

export const ZEEPO_REPLICATE_OFFICIAL_PRICING: ReplicateModelPricing[] = ${JSON.stringify(models, null, "\t")} as ReplicateModelPricing[];

export const ZEEPO_REPLICATE_PRICING_BY_ID = new Map(
	ZEEPO_REPLICATE_OFFICIAL_PRICING.map((m) => [m.id, m]),
);
`;

fs.writeFileSync(outPath, header + body);
console.log("Wrote", outPath, `(${models.length} models)`);
